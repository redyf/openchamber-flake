#!/usr/bin/env nix-shell
#! nix-shell -i bash -p curl jq nix coreutils

# Updates sources.nix to the latest OpenChamber release.
# Hashes come from GitHub's release asset digests, so no AppImage is downloaded.
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"

release="$(curl -fsSL https://api.github.com/repos/openchamber/openchamber/releases/latest)"
version="$(jq -r '.tag_name | ltrimstr("v")' <<<"$release")"

sri() {
  local digest
  digest="$(jq -r --arg name "$1" '.assets[] | select(.name == $name) | .digest' <<<"$release")"
  if [[ -z "$digest" || "$digest" == "null" ]]; then
    echo "error: no digest for $1" >&2
    exit 1
  fi
  nix hash convert --hash-algo sha256 --to sri "${digest#sha256:}"
}

x86_64_hash="$(sri "OpenChamber-${version}-linux-x86_64.AppImage")"
aarch64_hash="$(sri "OpenChamber-${version}-linux-arm64.AppImage")"

cat >sources.nix <<EOF
# Generated by ./update.sh. Do not edit manually.
{
  version = "${version}";
  hashes = {
    x86_64-linux = "${x86_64_hash}";
    aarch64-linux = "${aarch64_hash}";
  };
}
EOF

echo "openchamber ${version}"
echo "  x86_64-linux  $x86_64_hash"
echo "  aarch64-linux $aarch64_hash"
